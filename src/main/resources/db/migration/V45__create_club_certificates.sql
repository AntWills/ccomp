CREATE TABLE tb_club_certificate_settings (
    club_id bigint PRIMARY KEY REFERENCES tb_clubs(id) ON DELETE CASCADE,
    member_workload_hours numeric(8, 2) NOT NULL DEFAULT 0 CHECK (member_workload_hours >= 0),
    instructor_workload_hours numeric(8, 2) NOT NULL DEFAULT 0 CHECK (instructor_workload_hours >= 0),
    updated_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tb_club_certificate_validation_code (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(16) NOT NULL UNIQUE,
    club_id bigint NOT NULL REFERENCES tb_clubs(id) ON DELETE CASCADE,
    user_id uuid NOT NULL,
    certificate_type varchar(20) NOT NULL CHECK (certificate_type IN ('MEMBER', 'INSTRUCTOR')),
    workload_hours numeric(8, 2) NOT NULL CHECK (workload_hours >= 0),
    created_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_club_certificate_recipient_type UNIQUE (club_id, user_id, certificate_type)
);
CREATE INDEX idx_club_certificate_club ON tb_club_certificate_validation_code(club_id);
CREATE INDEX idx_club_certificate_user ON tb_club_certificate_validation_code(user_id);
