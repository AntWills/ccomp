CREATE TABLE tb_club_materials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id bigint NOT NULL REFERENCES tb_clubs(id) ON DELETE CASCADE,
    title varchar(255) NOT NULL,
    description varchar(1000),
    type varchar(10) NOT NULL CHECK (type IN ('LINK', 'FILE', 'IMAGE')),
    url varchar(2048),
    file_key varchar(512),
    original_file_name varchar(255),
    content_type varchar(100),
    size_bytes bigint,
    created_by uuid NOT NULL,
    created_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_club_material_target CHECK (
        (type = 'LINK' AND url IS NOT NULL AND file_key IS NULL AND original_file_name IS NULL AND content_type IS NULL AND size_bytes IS NULL)
        OR
        (type IN ('FILE', 'IMAGE') AND url IS NULL AND file_key IS NOT NULL AND original_file_name IS NOT NULL AND content_type IS NOT NULL AND size_bytes IS NOT NULL AND size_bytes > 0)
    )
);
CREATE INDEX idx_club_materials_club_created ON tb_club_materials(club_id, created_at DESC, id DESC);
CREATE UNIQUE INDEX uk_club_materials_file_key ON tb_club_materials(file_key) WHERE file_key IS NOT NULL;
