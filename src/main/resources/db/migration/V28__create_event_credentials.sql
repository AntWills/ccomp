ALTER TABLE tb_event_enrollments
    ADD CONSTRAINT uk_event_enrollment_id UNIQUE (events_id, id);

CREATE TABLE tb_event_credentials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id bigint NOT NULL,
    enrollment_id bigint NOT NULL,
    credentialed_at timestamp(6),
    credentialed_by uuid,
    station varchar(50),
    badge_print_count integer NOT NULL DEFAULT 0 CHECK (badge_print_count >= 0),
    last_badge_printed_at timestamp(6),
    token_hash varchar(64),
    token_updated_at timestamp(6),
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT uk_event_credentials_event_enrollment UNIQUE (event_id, enrollment_id),
    CONSTRAINT uk_event_credentials_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_event_credentials_enrollment FOREIGN KEY (event_id, enrollment_id)
        REFERENCES tb_event_enrollments (events_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_event_credentials_actor FOREIGN KEY (credentialed_by) REFERENCES tb_users (id)
);

CREATE INDEX idx_event_credentials_event_credentialed_at
    ON tb_event_credentials (event_id, credentialed_at, id);

CREATE TABLE tb_event_credential_operators (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id bigint NOT NULL,
    user_id uuid NOT NULL,
    granted_by uuid NOT NULL,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_event_credential_operators_event_user UNIQUE (event_id, user_id),
    CONSTRAINT fk_event_credential_operators_event FOREIGN KEY (event_id) REFERENCES tb_events (id) ON DELETE CASCADE,
    CONSTRAINT fk_event_credential_operators_user FOREIGN KEY (user_id) REFERENCES tb_users (id) ON DELETE CASCADE,
    CONSTRAINT fk_event_credential_operators_granted_by FOREIGN KEY (granted_by) REFERENCES tb_users (id)
);

CREATE INDEX idx_event_credential_operators_user_event
    ON tb_event_credential_operators (user_id, event_id);

